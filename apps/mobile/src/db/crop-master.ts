/** 作物の sourceIds を出典の行に引き直す。順序は CROP_MASTER_REFERENCES のまま */
export function referencesFor(sourceIds: readonly string[]): CropReference[] {
  const wanted = new Set(sourceIds);
  return CROP_MASTER_REFERENCES.filter((ref) => wanted.has(ref.id));
}

/** id でマスターを引く（ガイド画面の出典など、DB に持たない値のため） */
export function findCropMaster(cropId: string): CropMaster | undefined {
  return CROP_MASTER.find((crop) => crop.id === cropId);
}

