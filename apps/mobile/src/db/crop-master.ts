export interface CropTask {
  kind: CropTaskKind;
  /** 植え付け（または種まき）からの日数 */
  afterDays: number;
  /** 一言（「本葉 5〜6 枚で」など）。無ければラベルだけ出す */
  note?: string;
}

/** 出典と突き合わせる値。県指針・種袋の裏に載る範囲だけ */
export interface CropGuideMaster {
  /** 株間の目安（cm） */
  spacingCm: number;
  /** full=日なた / partial=半日陰 */
  sunlight: 'full' | 'partial';
  wateringNote: string;
  /** 水やりの目安間隔（日）。R26 ケアスケジュール自動提案の既定値。雨まかせなら null */
  wateringIntervalDays: number | null;
  /** 発芽までの日数。苗から始める作物は null */
  germinationDays: number | null;
  /** 種まきから定植までの日数（苗物だけ）。R33 定植適期の材料 */
  transplantAfterDays: number | null;
  /** 植え付け（または種まき）から初回の追肥までの日数。R10 の判定に使う */
  fertilizeAfterDays: number | null;
  /** 2 回目以降の追肥間隔（日）。1 回で済む作物は null */
  fertilizeIntervalDays: number | null;
  /** 植え付け（または種まき）から収穫までの日数。R10 の判定に使う。多年草は null */
  harvestAfterDays: number | null;
  /** 収穫の幅（最短〜最長）。進行帯に「窓」を描く。多年草は null */
  harvestWindowDays: { min: number; max: number } | null;
  /** 初収穫から採り続けられる日数。一度で採り切る作物は null */
  harvestDurationDays: number | null;
  /** 発芽適温・生育適温（℃）。WBS 4.13 の天気連携と R33 が使う */
  temperature: { germination: [number, number]; growth: [number, number] } | null;
  /** 連作を避ける年数。0 = 連作障害が出にくい。R17 は科だけでは足りない */
  rotationYears: number | null;
  /** 作物ごとの作業（摘芯・支柱・土寄せ…）。日数順 */
  tasks: CropTask[];
  /** 気をつける虫・病気 */
  commonPests: string[];
  tips: string;
}

/** 出典なしの判断。一覧の絞り込みと登録時の助言にだけ使い、暦や次の作業の判定には使わない */
export interface CropEditorial {
  /** 初心者向けか */
  beginner: boolean;
  /** プランターで育つか。育つなら必要な深さ（cm） */
  container: { ok: true; depthCm: number } | { ok: false };
}

export interface CropMaster {
  id: string;
  name: string;
  /** ひらがな。検索の読み仮名 */
  nameReading: string;
  /** 科。R17 連作障害チェックの判定キー */
  family: string;
  category: CropCategory;
  /** 収穫の既定単位（HARVEST_UNITS の語彙） */
  defaultUnit: 'piece' | 'g' | 'kg' | 'bunch' | 'plant';
  /** 多年草。収穫日数を持たず、ガイドに「翌年から収穫」と出す */
  perennial?: true;
  /** CROP_MASTER_REFERENCES の id。1 つ以上 */
  sourceIds: string[];
  calendars: CropCalendarWindow[];
  guide: CropGuideMaster;
  editorial: CropEditorial;
}

